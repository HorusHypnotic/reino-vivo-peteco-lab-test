const assert=require('node:assert/strict');const fs=require('node:fs');const vm=require('node:vm');
const src=fs.readFileSync(require('node:path').join(__dirname,'../v18/art-bridge.js'),'utf8');
const ctx={};vm.runInNewContext(src,ctx);
const art=ctx.PetecoArtBridgeV18;assert.ok(art);
const low=art.scene({level:1,people:2,project:0},0);
const high=art.scene({level:78,people:80,project:10,projectGoal:30},2);
assert.equal(low.buildings.length,0,'do not fabricate buildings without structures');
assert.equal(high.buildings.length,0,'population and level do not imply real structures');
assert.equal(high.workers.length,0,'population does not prove worker actions');
assert.equal(high.tier,5);assert.equal(high.biome,'highlands');
const saved={level:78,people:80,project:10,projectGoal:30,structures:[{id:0,stage:0,integrity:0},{id:1,stage:1,integrity:80}],artWorkers:[{id:'logger-1',x:44,y:188,job:'woodcut',phase:'working'}]};
