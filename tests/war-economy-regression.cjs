'use strict';
const assert = require('node:assert/strict');
const economy = require('../v7/war-economy.js');
const labor = require('../v7/labor.js');
const fs = require('node:fs');
const html = fs.readFileSync(require('node:path').join(__dirname, '..', 'index.html'), 'utf8');
const trade = require('../v7/trade.js');
const s = trade.create();
trade.sync(s, { players: {} }, ['BR-PA', 'BR-BA']);
s.villages['BR-PA'].stock = { wood: 2, food: 40, stone: 3 };
s.villages['BR-BA'].stock = { wood: 30, food: 10, stone: 20 };
let w = economy.create();
const plan = economy.settle(w, s, { warId: 'war-7', winner: 'BR-BA', loser: 'BR-PA' });
assert.equal(plan.ok, true);
assert.equal(economy.isBlocked(plan.state, 'BR-PA', 'BR-BA'), true);
assert.deepEqual(plan.state.charges[0].cost, { wood: 2, stone: 3 });
const repeated = economy.settle(plan.state, s, { warId: 'war-7', winner: 'BR-BA', loser: 'BR-PA' });
assert.equal(repeated.duplicate, true);
assert.equal(plan.state.charges.length, 1, 'settling a war twice does not create a second charge');
assert.equal(s.villages['BR-PA'].stock.wood, 2, 'preparing a journal does not debit stock');
let checkpoint = economy.reconcile(plan.state, s);
assert.equal(checkpoint.trade.villages['BR-PA'].stock.wood, 0);
assert.equal(checkpoint.trade.villages['BR-PA'].stock.stone, 0);
assert.equal(s.villages['BR-PA'].stock.wood, 2, 'discarded checkpoint simulates a failed storage write without mutating source');
// Retry after a failed checkpoint; then recover if the stock checkpoint lands before journal progress.
const beforeFailedWrite = JSON.stringify(s);
const failedRetry = economy.reconcile(plan.state, s);
assert.equal(JSON.stringify(s), beforeFailedWrite, 'a discarded failed checkpoint leaves the original economy untouched');
checkpoint = economy.reconcile(plan.state, s);
s.villages = checkpoint.trade.villages; s.warLedger = checkpoint.trade.warLedger;
const recovered = economy.reconcile(plan.state, s);
w = recovered.state;
assert.equal(recovered.trade.villages['BR-PA'].stock.wood, 0);
assert.deepEqual(recovered.state.settlements['war-7'].repairPaid, { wood: 2, stone: 3 });
assert.equal(failedRetry.trade.villages['BR-PA'].stock.wood, 0);
assert.equal(economy.reconcile(plan.state, checkpoint.trade).trade.villages['BR-PA'].stock.wood, 0, 'checkpoint-first recovery replays the ledger without a second debit');

// Autonomous production supplies the remaining wood; only the resulting cost is journaled.
const laborState = labor.create(); labor.sync(laborState);
labor.step(laborState, s);
assert.equal(s.villages['BR-PA'].stock.wood, 3);
const repair = economy.repair(w, s, 'war-7');
assert.equal(repair.changed, true);
assert.deepEqual(repair.state.charges.at(-1).cost, { wood: 3, stone: 0 });
const repaired = economy.reconcile(repair.state, s);
assert.deepEqual(repaired.state.settlements['war-7'].repairPaid, { wood: 5, stone: 3 });
assert.equal(repaired.trade.villages['BR-PA'].stock.wood, 0);
w = repaired.state; s.warLedger = repaired.trade.warLedger; s.villages = repaired.trade.villages;
assert.equal(economy.routeStatus(w, 'BR-PA', 'BR-BA').recovery, 0);
for (let i=0;i<4;i++) economy.advance(w);
assert.equal(economy.isBlocked(w, 'BR-PA', 'BR-BA'), false);
assert.equal(economy.routeStatus(w, 'BR-PA', 'BR-BA').recovery, 1);

// Scarcity/no partner blocks only the route at war; normal trade resumes as it recovers.
const shortage = trade.create();
trade.sync(shortage, { players: {} }, ['BR-PA', 'BR-BA']);
shortage.villages['BR-PA'].stock = { wood: 30, food: 10, stone: 20 };
shortage.villages['BR-BA'].stock = { wood: 10, food: 40, stone: 20 };
let out = trade.step(shortage, { isBlocked: (a,b) => economy.isBlocked(plan.state,a,b) });
assert.equal(out.reason, 'no-partner');
for (let i=0;i<2;i++) economy.advance(plan.state);
out = trade.step(shortage, { isBlocked: (a,b) => economy.isBlocked(plan.state,a,b) });
assert.equal(out.ok, true);
assert.ok(Object.values(shortage.villages).every(v => Object.values(v.stock).every(n => n >= 0)));
assert.equal(economy.restore(JSON.stringify(w)).settlements['war-7'].winner, 'BR-BA');
const migrated = economy.importLegacy(economy.create(), 'legacy-1', { winner: 'BR-PA', loser: 'BR-BA', repairCost: { wood: 2, stone: 1 } });
assert.deepEqual(migrated.state.settlements['legacy-1'].repairPaid, { wood: 2, stone: 1 });
assert.equal(migrated.state.charges.length, 0, 'legacy migration preserves already-paid materials without charging again');
const secondWar = economy.settle(w, s, { warId: 'war-8', winner: 'BR-BA', loser: 'BR-PA' });
assert.equal(secondWar.state.routes[economy.pair('BR-PA', 'BR-BA')].wars, 2, 'concurrent wars accumulate on the same route');
assert.match(html, /PetecoWarEconomy\.isBlocked\(warEconomyState,from,to\)/);
assert.match(html, /PetecoWarEconomy\.reconcile\(warEconomyState,tradeState\)/);
assert.match(html, /PetecoWarEconomy\.repair\(warEconomyState,tradeState,record\.warId\)/);
assert.match(html, /migrateLegacyWarRepairs\(\)/);
assert.match(html, /if\(!record\.repairPending\|\|!record\.warId/);
console.log('PASS route interruption/recovery, scarcity, idempotent settlement, checkpoint retry, and nonnegative stock');
