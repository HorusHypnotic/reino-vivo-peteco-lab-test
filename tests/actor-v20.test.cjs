const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const sandbox={};for(const name of ['factory-core','scene-map','actor-controller'])vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../v20/'+name+'.js'),'utf8'),sandbox);
const f=sandbox.PetecoFactoryV20,m=sandbox.PetecoSceneMapV20,a=sandbox.PetecoActorV20;
assert.equal(a.create(f,m,'unknown'),null);
const worker=a.create(f,m,'farm');assert.equal(worker.snapshot().phase,'idle');
assert.equal(worker.start({job:'farm',action:'harvest',cycle:1,confirmed:false,id:'farm:1:harvest'}),false);
assert.equal(worker.start({job:'farm',action:'harvest',cycle:1,confirmed:true,id:'farm:1:harvest'}),true);
for(let i=0;i<6;i++)worker.tick(.1);
assert.equal(worker.snapshot().phase,'work');
for(let i=0;i<7;i++)worker.tick(.1);
assert.equal(worker.snapshot().phase,'return');
for(let i=0;i<6;i++)worker.tick(.1);
assert.equal(worker.snapshot().phase,'idle');
assert.equal(worker.snapshot().x,m.route('farm').depot.x);
assert.equal(worker.start(f.event({job:'farm',action:'plant',cycle:2,confirmed:true})),true);
worker.cancel();assert.equal(worker.snapshot().phase,'idle');
assert.equal(worker.snapshot().pending,false);
const miner=a.create(f,m,'quarry');assert.equal(miner.start(f.event({job:'quarry',action:'mine',cycle:4,confirmed:true})),true);
assert.equal(miner.start(f.event({job:'quarry',action:'mine',cycle:5,confirmed:true})),true);
assert.equal(miner.snapshot().pending,true);
console.log('PASS V20 actor lifecycle, confirmed gate, queue and cancel');
